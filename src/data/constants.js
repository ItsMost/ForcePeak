/**
 * Classify any drill (whether legacy or new) into one of the 8 elite categories
 * for clean, non-destructive filtering and visualization.
 */
export function getUnifiedCategory(drill) {
  if (!drill) return 'max_strength_lower';
  const explicitCategory = (drill.category || '').toLowerCase().trim();
  if (ELITE_EXERCISE_CATEGORIES[explicitCategory]) return explicitCategory;

  const rawType = (drill.type || '').toLowerCase().trim();
  if (ELITE_EXERCISE_CATEGORIES[rawType]) return rawType;

  if (rawType === 'core') return 'trunk_rotation';
  if (rawType === 'plyometric') return 'elasticity_plyo';
  if (rawType === 'power') return 'rofd_ballistics';
  if (rawType === 'isometric') return 'isometric_tendon';
  if (rawType === 'speed' || rawType === 'endurance') return 'sprint_speed';
  if (rawType === 'mobility' || rawType === 'recovery' || rawType === 'warmup') return 'prehab_mobility';

  const t = ((drill.title || drill.name || '') + ' ' + (drill.subcategory || '')).toLowerCase();
  const upperKeywords = ['bench', 'press', 'dip', 'pull-up', 'pull up', 'row', 'lat', 'overhead', 'shoulder', 'arm', 'bicep', 'tricep', 'chest', 'incline', 'push up', 'push-up'];
  if (upperKeywords.some(kw => t.includes(kw))) {
    return 'max_strength_upper';
  }
  return 'max_strength_lower';
}

